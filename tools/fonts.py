#!/usr/bin/env python3
"""Self-host the site's Google Fonts.

    python3 tools/fonts.py

Downloads the exact WOFF2 files Google Fonts serves into assets/fonts/ and
writes their @font-face rules between the `/* fonts:start */` and
`/* fonts:end */` markers of each target below. Run it from the repo root
after changing a family or weight here, or the greeting words on the home
page: the intro greeting's non-Latin scripts are subset to just the glyphs in
index.html's data-words, so new words need new files.
"""
import glob
import hashlib
import html
import json
import os
import re
import sys
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, 'assets', 'fonts')
API = 'https://fonts.googleapis.com/css2?'
# a current Chrome UA, so Google answers with WOFF2 split into unicode-range subsets
UA = ('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
      '(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36')

SITE = ('family=Bricolage+Grotesque:opsz,wght@12..96,400;12..96,500;12..96,600;12..96,700;12..96,800'
        '&family=Hanken+Grotesk:wght@400;500;600&family=JetBrains+Mono:wght@400;500&display=swap')
GREETING = ('family=Noto+Sans+Arabic:wght@400&family=Noto+Sans+Devanagari:wght@400'
            '&family=Noto+Sans+KR:wght@400&family=Noto+Sans+JP:wght@400&display=swap')
ORFYX = 'family=Inter:wght@400;500;600;700;800;900&display=swap'
GENERATED = set()   # file names written this run


def greeting_text():
    """Every non-ASCII character in the home page's typed greetings."""
    with open(os.path.join(ROOT, 'index.html'), encoding='utf-8') as f:
        m = re.search(r'class="tw" data-words=\'([^\']+)\'', f.read())
    words = json.loads(html.unescape(m.group(1)))
    return ''.join(sorted({c for w in words for c in w if ord(c) > 0x24F}))


def get(url):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def slug(s):
    return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')


def faces(query, tag=''):
    """@font-face rules for one css2 query, with the files saved locally.
    Google repeats a variable font once per weight with the same file; those
    collapse into one rule with a weight range."""
    css = get(API + query).decode()
    rules = {}
    for subset, body in re.findall(r'(?:/\* ([\w-]+) \*/\s*)?@font-face\s*{([^}]*)}', css):
        props = dict((k.strip(), v.strip()) for k, v in
                     (line.split(':', 1) for line in body.strip().rstrip(';').split(';\n')))
        src = re.search(r'url\(([^)]+)\)', props['src']).group(1)
        family = props['font-family'].strip("'")
        rule = rules.setdefault(src, {**props, 'family': family, 'subset': subset or tag, 'weights': []})
        rule['weights'].append(int(props['font-weight']))
    out = []
    for src, r in rules.items():
        lo, hi = min(r['weights']), max(r['weights'])
        data = get(src)
        # the content hash in the name lets vercel.json cache fonts forever
        name = f"{slug(r['family'])}-{r['subset']}-{hashlib.sha1(data).hexdigest()[:8]}.woff2"
        path = os.path.join(FONT_DIR, name)
        GENERATED.add(name)
        if not os.path.exists(path):
            with open(path, 'wb') as f:
                f.write(data)
        lines = [f"font-family:'{r['family']}'", f"font-style:{r['font-style']}",
                 f"font-weight:{lo}" + (f' {hi}' if hi != lo else '')]
        if 'font-stretch' in r:
            lines.append(f"font-stretch:{r['font-stretch']}")
        lines += [f"font-display:{r['font-display']}", f"src:url(/assets/fonts/{name}) format('woff2')"]
        if 'unicode-range' in r:
            lines.append(f"unicode-range:{r['unicode-range']}")
        out.append(f"/* {r['family']}, {r['subset']} */\n@font-face{{{';'.join(lines)}}}")
    return out


def write(target, rules, note):
    path = os.path.join(ROOT, target)
    with open(path, encoding='utf-8') as f:
        text = f.read()
    block = f'/* fonts:start (generated by tools/fonts.py: {note}) */\n' + '\n'.join(rules) + '\n/* fonts:end */'
    new, n = re.subn(r'/\* fonts:start.*?/\* fonts:end \*/', lambda _: block, text, flags=re.S)
    if n != 1:
        sys.exit(f'{target}: expected one fonts:start ... fonts:end block, found {n}')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(new)
    print(f'{target}: {len(rules)} @font-face rules')


if __name__ == '__main__':
    os.makedirs(FONT_DIR, exist_ok=True)
    text = urllib.parse.quote(greeting_text())
    write('assets/site.css', faces(SITE) + faces(f'{GREETING}&text={text}', 'greeting'),
          'Bricolage Grotesque, Hanken Grotesk, JetBrains Mono, and the greeting subsets')
    write('orfyx-design-system.html', faces(ORFYX), 'Inter')
    # point <link rel="preload"> tags at the current file names
    current = {re.sub(r'-[0-9a-f]{8}\.woff2$', '', n): n for n in GENERATED}
    for page in glob.glob(os.path.join(ROOT, '*.html')) + glob.glob(os.path.join(ROOT, 'work', '*.html')):
        with open(page, encoding='utf-8') as f:
            text = f.read()
        new = re.sub(r'/assets/fonts/([\w-]+?)-[0-9a-f]{8}\.woff2',
                     lambda m: '/assets/fonts/' + current.get(m.group(1), m.group(0).split('/')[-1]), text)
        if new != text:
            with open(page, 'w', encoding='utf-8') as f:
                f.write(new)
            print('preload updated in', os.path.relpath(page, ROOT))
    for stale in sorted(set(os.listdir(FONT_DIR)) - GENERATED):
        os.remove(os.path.join(FONT_DIR, stale))
        print('removed', stale)
